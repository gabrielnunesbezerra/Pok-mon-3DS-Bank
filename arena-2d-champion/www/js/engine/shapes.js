// Forma padrão quando o golpe não está na tabela acima
export function shapeFor(id) {
  if (SHAPES[id]) return SHAPES[id];
  const m = MOVES[id];
  if (!m) return lunge();
  const has = f => m.flags.includes(f);
  if (m.cat === 'Status') {
    if (['self', 'allySide', 'allies', 'adjacentAlly', 'all', 'foeSide'].includes(m.target)) return self();
    if (has('sound')) return ring(260, { sound: true });
    if (has('powder')) return sproj('powder', 380, { range: 300, size: 22 });
    return gaze();
  }
  if (has('contact')) return has('slicing') ? slash() : lunge();
  if (has('sound')) return ring(260, { sound: true });
  if (has('wind')) return cone(280, 55);
  return proj();
}
